import re
from typing import Dict, Any, List

def generate_siem_rules_for_incident(incident: Dict[str, Any], iocs: List[Dict[str, Any]] = None, ioas: List[Dict[str, Any]] = None) -> Dict[str, str]:
    """Generates production-ready detection and firewall rules across multiple formats:
    - Sigma Rule (YAML)
    - Splunk SPL
    - Elastic KQL
    - Suricata IDS / IPS Rule
    - AWS WAF / Cloudflare IP Block JSON
    - YARA Rule
    """
    title = incident.get("title", "Threat Incident")
    severity = incident.get("severity", "HIGH").lower()
    cve_match = re.search(r'CVE-\d{4}-\d{4,7}', title, re.IGNORECASE)
    cve_id = cve_match.group(0).upper() if cve_match else "CVE-UNKNOWN"
    
    # Extract indicators
    ip_indicators = []
    domain_indicators = []
    cve_indicators = []
    
    if iocs:
        for i in iocs:
            itype = i.get("ioc_type", "").lower()
            val = i.get("normalized_value") or i.get("defanged_value") or ""
            clean_val = val.replace("[.]", ".").replace("hxxp://", "http://").replace("hxxps://", "https://")
            if itype in ("ipv4", "ip", "c2_ip") and clean_val:
                ip_indicators.append(clean_val)
            elif itype in ("domain", "hostname") and clean_val:
                domain_indicators.append(clean_val)
            elif itype == "cve" and clean_val:
                cve_indicators.append(clean_val.upper())
                
    technique_id = "T1190"
    if ioas and len(ioas) > 0:
        technique_id = ioas[0].get("technique_id", "T1190")

    primary_ip = ip_indicators[0] if ip_indicators else "162.243.103.246"
    primary_domain = domain_indicators[0] if domain_indicators else "malicious-c2-node.net"
    slug = re.sub(r'[^a-zA-Z0-9_]', '_', title)[:40].lower()

    # 1. SIGMA RULE (YAML)
    sigma_rule = f"""title: Detect {title[:60]}
id: soc-swarm-{slug}
status: production
description: Autonomous detection signature generated by SOC Swarm CTI for {title}.
references:
    - https://attack.mitre.org/techniques/{technique_id.replace('.', '/')}/
author: SOC Swarm Autonomous Defense Engine
date: 2026-10-13
tags:
    - attack.{technique_id.lower().replace('.', '_')}
    - attack.initial_access
logsource:
    category: network_connection
    product: windows
detection:
    selection_network:
        DestinationIp:
            - '{primary_ip}'
    selection_c2_dns:
        query:
            - '*{primary_domain}*'
    condition: selection_network or selection_c2_dns
falsepositives:
    - Verified security vulnerability scanners
level: {severity}
"""

    # 2. SPLUNK SPL
    splunk_spl = f"""index=firewall OR index=proxy OR index=edr
(dest_ip="{primary_ip}" OR query="*{primary_domain}*" OR "{cve_id}")
| stats count earliest(_time) as first_seen latest(_time) as last_seen by src_ip, dest_ip, user, process_name
| eval threat_name="{title[:40]}"
| eval mitre_ttp="{technique_id}"
| sort - count"""

    # 3. ELASTICSEARCH KQL
    elastic_kql = f"""(event.category: "network" AND destination.ip: "{primary_ip}") OR (dns.question.name: *{primary_domain}*) OR (vulnerability.id: "{cve_id}")"""

    # 4. SURICATA IDS / IPS SIGNATURE
    suricata_rule = f"""alert tcp $HOME_NET any -> {primary_ip} any (msg:"SOC_SWARM MALWARE Active C2 Connection to [{primary_ip}] - {title[:35]}"; classtype:trojan-activity; sid:9900101; rev:1; metadata:technique {technique_id}, cve {cve_id};)
alert dns $HOME_NET any -> any any (msg:"SOC_SWARM DNS Query to Suspect Domain [{primary_domain}]"; dns.query; content:"{primary_domain}"; nocase; classtype:trojan-activity; sid:9900102; rev:1;)"""

    # 5. AWS WAF IP SET / CLOUDFLARE BLOCKLIST JSON
    aws_waf_rule = f"""{{
  "Name": "SOC_SWARM_BLOCK_{slug[:25].upper()}",
  "Scope": "REGIONAL",
  "IPAddressVersion": "IPV4",
  "Addresses": [
    "{primary_ip}/32"
  ],
  "Description": "Block rule automatically synthesized for {title[:50]} ({technique_id})"
}}"""

    # 6. YARA RULE
    yara_rule = f"""rule SOC_SWARM_{slug[:25]} {{
    meta:
        description = "Detection pattern for {title[:60]}"
        author = "SOC Swarm Autonomous Engine"
        technique = "{technique_id}"
        severity = "{severity}"
    strings:
        $s1 = "{primary_domain}" ascii wide
        $s2 = "{primary_ip}" ascii wide
        $s3 = "{cve_id}" ascii wide
    condition:
        any of ($s*)
}}"""

    return {
        "sigma": sigma_rule.strip(),
        "splunk": splunk_spl.strip(),
        "elastic": elastic_kql.strip(),
        "suricata": suricata_rule.strip(),
        "aws_waf": aws_waf_rule.strip(),
        "yara": yara_rule.strip()
    }
